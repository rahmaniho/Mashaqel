export function seedFormulaVersions(db: Db): void {
  const stmt = db.raw.prepare(`
    INSERT INTO formula_versions (
      formula_code, formula_name, calculation_description, expression_spec, version,
      effective_from, effective_to, currency_unit, legal_source, circular_number,
      validity_status, legal_document_id
    ) VALUES (?, ?, ?, ?, ?, ?, ?, 'IRR', ?, ?, ?, ?)
    ON CONFLICT(formula_code, version) DO UPDATE SET
      formula_name = excluded.formula_name,
      calculation_description = excluded.calculation_description,
      expression_spec = excluded.expression_spec,
      legal_source = excluded.legal_source,
      circular_number = excluded.circular_number,
      validity_status = excluded.validity_status,
      last_modified_at = datetime('now')
  `);
  for (const f of FORMULA_VERSIONS) {
    const docId = f.legalDocumentCode ? getLegalDocumentId(db, f.legalDocumentCode) : null;
    stmt.run(
      f.formulaCode,
      f.formulaName,
      f.calculationDescription,
      f.expressionSpec,
      f.version,
      f.effectiveFrom,
      f.effectiveTo,
      f.legalSource,
      f.circularNumber,
      f.validityStatus,
      docId,
    );
  }
}
